/**
 * Shared domain types for the AI-Powered Recipe Finder.
 *
 * These types describe the in-memory shape of recipes, pantry scans,
 * detected ingredients, and matching results. Persistence is handled
 * separately (Prisma) and uses JSON-serialized strings for nested fields.
 */

export type RecipeTag =
  | "vegetarian"
  | "vegan"
  | "gluten-free"
  | "dairy-free"
  | "keto"
  | "whole30";

export type Difficulty = "easy" | "medium" | "hard";

export interface IngredientRef {
  /** Ingredient name, lowercase canonical form (e.g. "olive oil"). */
  name: string;
  /** Human-readable quantity, e.g. "2 cloves", "1 cup", "200 g". */
  quantity: string;
}

export interface Macros {
  /** kcal per serving. */
  calories: number;
  /** grams of protein per serving. */
  protein: number;
  /** grams of carbs per serving. */
  carbs: number;
  /** grams of fat per serving. */
  fat: number;
}

export interface Recipe {
  id: string;
  title: string;
  cuisine: string;
  ingredients: IngredientRef[];
  instructions: string[];
  prepTime: number; // minutes
  cookTime: number; // minutes
  servings: number;
  macros: Macros; // per serving
  tags: RecipeTag[];
  difficulty: Difficulty;
}

export interface DetectedIngredient {
  name: string;
  /** Optional estimated quantity, e.g. "2 cups", "~200 g". */
  quantity?: string;
  /** Model confidence in the detection, 0..1. */
  confidence?: number;
}

export interface PantryItem {
  name: string;
  quantity?: string;
}

export interface MatchedRecipe {
  recipe: Recipe;
  /** 0..1 fraction of recipe ingredients found in the pantry. */
  matchPercent: number;
  /** Ingredient names the pantry is missing. */
  missingIngredients: string[];
  /** Ingredient names the pantry has. */
  matchedIngredients: string[];
}

export interface SwapSuggestion {
  /** The original missing ingredient name. */
  ingredient: string;
  /** The suggested substitute as a user-facing phrase. */
  substitute: string;
  /** Whether the swap was generated by the LLM or pulled from the swap table. */
  source: "table" | "llm" | "none";
}
